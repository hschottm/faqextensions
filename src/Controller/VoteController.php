<?php

declare(strict_types=1);

namespace Hschottm\FaqExtensionsBundle\Controller;

use Contao\CoreBundle\Csrf\ContaoCsrfTokenManager;
use Contao\FrontendUser;
use FOS\HttpCache\CacheInvalidator;
use Hschottm\FaqExtensionsBundle\Voting\VoteRecorder;
use Hschottm\FaqExtensionsBundle\Voting\VoterIdentity;
use Symfony\Component\HttpFoundation\Cookie;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Security\Core\Authentication\Token\Storage\TokenStorageInterface;
use Symfony\Component\Security\Csrf\CsrfToken;
use Twig\Environment;

final class VoteController
{
    public function __construct(
        private readonly VoteRecorder $recorder,
        private readonly VoterIdentity $identity,
        private readonly ContaoCsrfTokenManager $csrf,
        private readonly string $csrfTokenName,
        private readonly TokenStorageInterface $tokens,
        private readonly Environment $twig,
        private readonly ?CacheInvalidator $cacheInvalidator = null,
    ) {
    }

    public function __invoke(Request $request, int $id, int $vote): Response
    {
        // Only links generated by a rendered FAQ may open the voting page.
        // This also prevents guessing IDs to display otherwise unlinked questions.
        if (!$this->identity->isVoteSignatureValid($id, $vote, (string) $request->query->get('signature', ''))) {
            return new Response('Invalid voting link.', 403, ['Cache-Control' => 'private, no-store, max-age=0']);
        }
        $faq = $this->recorder->findFaq($id);
        $cookie = (string) $request->cookies->get(VoterIdentity::COOKIE, '');
        $validCookie = $this->identity->isValid($cookie);
        $user = $this->tokens->getToken()?->getUser();
        $memberId = $user instanceof FrontendUser ? (int) $user->id : null;
        $status = 'confirm';
        $httpStatus = 200;

        if (!$faq || !in_array($vote, [-1, 1], true)) {
            $status = 'unavailable';
            $httpStatus = 404;
        } elseif ($request->isMethod('POST')) {
            // Requiring the cookie also prevents Contao's cookieless-CSRF bypass.
            if (!$validCookie || !$this->csrf->isTokenValid(new CsrfToken($this->csrfTokenName, (string) $request->request->get('REQUEST_TOKEN', '')))) {
                $status = 'invalid';
                $httpStatus = 400;
            } else {
                $status = $this->recorder->record($id, $vote, $this->identity->keys($cookie, $memberId));
                if ($status === 'accepted') {
                    $this->cacheInvalidator?->invalidateTags(['contao.db.tl_faq.'.$id, 'contao.db.tl_faq_category.'.$faq['pid']]);
                }
                if ($status === 'unavailable') {
                    $httpStatus = 404;
                }
            }
        }

        $response = new Response($this->twig->render('@HschottmFaqExtensions/vote.html.twig', [
            'question' => $faq ? html_entity_decode($faq['question'], ENT_QUOTES | ENT_HTML5, 'UTF-8') : '',
            'vote' => $vote,
            'status' => $status,
            'locale' => $request->getLocale(),
            'token' => $status === 'confirm' ? $this->csrf->getDefaultTokenValue() : '',
            'returnUrl' => self::localReturnUrl((string) $request->query->get('return', '/')),
        ]), $httpStatus);
        $response->headers->set('Cache-Control', 'private, no-store, max-age=0');
        $response->headers->set('X-Robots-Tag', 'noindex, nofollow');
        $response->headers->set('Referrer-Policy', 'same-origin');
        if ($request->isMethod('GET') && $status === 'confirm') {
            $response->headers->setCookie(Cookie::create(VoterIdentity::COOKIE)
                ->withValue($validCookie ? $cookie : $this->identity->createCookie())
                ->withExpires(time() + 365 * 86400)
                ->withPath($request->getBasePath() ?: '/')
                ->withSecure($request->isSecure())->withHttpOnly(true)->withSameSite(Cookie::SAMESITE_LAX));
        }
        return $response;
    }

    private static function localReturnUrl(string $url): string
    {
        $decoded = rawurldecode($url);
        if (!str_starts_with($decoded, '/') || str_starts_with($decoded, '//') || preg_match('/[\\\\\x00-\x20]/', $decoded)) {
            return '/';
        }
        return $url;
    }
}
